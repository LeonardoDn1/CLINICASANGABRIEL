    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        String aseguradora = txtAseguradora.getText().trim();
        String numeroPoliza = txtNumeroPoliza.getText().trim();

        java.util.Date fechaInicio = jdcInicioVigencia.getDate();
        java.util.Date fechaFin = jdcFinVigencia.getDate();

        java.sql.Date vigenciaInicio = fechaInicio != null
                ? new java.sql.Date(fechaInicio.getTime())
                : null;

        java.sql.Date vigenciaFin = fechaFin != null
                ? new java.sql.Date(fechaFin.getTime())
                : null;

        SeguroMedico datos = new SeguroMedico();
        datos.setAseguradora(aseguradora);
        datos.setNumeroPoliza(numeroPoliza);
        datos.setVigenciaInicio(vigenciaInicio);
        datos.setVigenciaFin(vigenciaFin);

        // Mantener los identificadores cuando se agrega o modifica
        // el seguro de un paciente registrado
        if (seguro != null) {
            datos.setIdSeguro(seguro.getIdSeguro());
            datos.setIdPaciente(seguro.getIdPaciente());
        }

        // Registrar o actualizar directamente en la base de datos
        if (modoGestion) {
            int resultado;

            if (nuevoSeguroGestion) {
                resultado = bllSeguro.insertarSeguro(datos);
            } else {
                resultado = bllSeguro.actualizarSeguro(datos);
            }

            if (resultado == 0) {
                if (formularioPaciente != null) {
                    formularioPaciente.actualizarBotonSeguroGestion();
                }

                dispose();
            }

            return;
        }

        // Cuando el seguro todavía es temporal,
        // la validación también se ejecuta desde la BLL
        if (!bllSeguro.validarSeguro(datos)) {
            return;
        }

        if (formularioPaciente == null) {
            JOptionPane.showMessageDialog(this,
                    "No se encontró el formulario del paciente",
                    "Error", 0);
            return;
        }

        formularioPaciente.setSeguroTemporal(datos);

        JOptionPane.showMessageDialog(this,
                "Datos del seguro cargados correctamente",
                "Información", 1);

        dispose();
    }//GEN-LAST:event_btnGuardarActionPerformed

