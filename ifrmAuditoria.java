    /**
     * Evento al presionar "Consultar Auditoría"
     */
    private void btnConsultarAuditoriaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarAuditoriaActionPerformed
        // TODO add your handling code here:
        String usuarioFiltro = txtFiltroUsuario.getText().trim().toLowerCase();
        String moduloFiltro = (cmbFiltroModulo.getSelectedItem() != null) ? cmbFiltroModulo.getSelectedItem().toString() : "Todos";

        // Obtener las fechas elegidas directamente del JDateChooser
        Date fInicio = jdcFechaInicio.getDate();
        Date fFin = jdcFechaFin.getDate();

        // Si seleccionó Fecha Fin, ajustamos la hora al final del día (23:59:59)
        if (fFin != null) {
            Calendar cal = Calendar.getInstance();
            cal.setTime(fFin);
            cal.set(Calendar.HOUR_OF_DAY, 23);
            cal.set(Calendar.MINUTE, 59);
            cal.set(Calendar.SECOND, 59);
            fFin = cal.getTime();
        }

        // Obtener la auditoría y lista de usuarios desde la capa de negocio
        ArrayList<Auditoria> listaBase = bllAuditoria.listarAuditoria();
        ArrayList<Usuario> listaUsuarios = bllUsuario.listarUsuarios();

        DefaultTableModel model = crearModeloNoEditable(
                "ID", "Usuario", "Fecha", "Hora", "Módulo", "Operación"
        );

        if (listaBase != null) {
            for (Auditoria a : listaBase) {

                // 1. Mapear idUsuario a Username real (evita que salga "ID 1", "ID 18")
                String nombreUsuario = "Usuario (ID " + a.getIdUsuario() + ")";
                for (Usuario u : listaUsuarios) {
                    if (u.getIdUsuario() == a.getIdUsuario()) {
                        nombreUsuario = u.getUsername();
                        break;
                    }
                }

                // 2. Filtro por Username
                if (!usuarioFiltro.isEmpty() && !nombreUsuario.toLowerCase().contains(usuarioFiltro)) {
                    continue;
                }

                // 3. Filtro por Módulo
                if (!"Todos".equalsIgnoreCase(moduloFiltro) && !a.getModulo().equalsIgnoreCase(moduloFiltro)) {
                    continue;
                }

                // 4. Filtro por Rango de Fechas
                if (a.getFechaHora() != null) {
                    if (fInicio != null && a.getFechaHora().before(fInicio)) {
                        continue;
                    }
                    if (fFin != null && a.getFechaHora().after(fFin)) {
                        continue;
                    }
                }

                // Formatear Fecha y Hora por separado
                String fechaStr = (a.getFechaHora() != null) ? formatoFecha.format(a.getFechaHora()) : "N/A";
                String horaStr = (a.getFechaHora() != null) ? formatoHora.format(a.getFechaHora()) : "N/A";

                model.addRow(new Object[]{
                    a.getIdAuditoria(),
                    nombreUsuario,
                    fechaStr,
                    horaStr,
                    a.getModulo(),
                    a.getOperacion() + " - " + a.getDetalle()
                });
            }
        }

        tblAuditoria.setModel(model);
        configurarTablaAuditoria();
    }//GEN-LAST:event_btnConsultarAuditoriaActionPerformed

    private void ajustarAnchoColumnaOperacion() {

        int columnaOperacion = 5;
        int anchoCalculado = 350; // Ancho mínimo

        java.awt.FontMetrics metricas
                = tblAuditoria.getFontMetrics(tblAuditoria.getFont());

        for (int fila = 0; fila < tblAuditoria.getRowCount(); fila++) {

            Object valor = tblAuditoria.getValueAt(
                    fila,
                    columnaOperacion
            );

            if (valor != null) {
                int anchoTexto
                        = metricas.stringWidth(valor.toString()) + 40;

                anchoCalculado = Math.max(
                        anchoCalculado,
                        anchoTexto
                );
            }
        }

        // Evita que la columna sea demasiado pequeña o enorme
        anchoCalculado = Math.max(350, anchoCalculado);
        anchoCalculado = Math.min(800, anchoCalculado);

        tblAuditoria.getColumnModel()
                .getColumn(columnaOperacion)
                .setPreferredWidth(anchoCalculado);
    }

