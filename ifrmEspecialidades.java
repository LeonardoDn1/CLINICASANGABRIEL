    // 1. CARGA INICIAL Y CONFIGURACIÓN

    

    private void configurarEventos() {
        btnGuardar.addActionListener(e -> guardarEspecialidad());
        btnModificar.addActionListener(e -> modificarEspecialidad());
        btnLimpiar.addActionListener(e -> limpiarFormulario());

        // Evento al seleccionar una fila en la tabla
        tblEspecialidades.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && tblEspecialidades.getSelectedRow() != -1) {
                cargarEspecialidadSeleccionada();
            }
        });
    }


    /**
     * RN-12, RN-46: Registra una nueva especialidad médica.
     */
    private void guardarEspecialidad() {
        String nombre = txtNombreEspecialidad.getText().trim();

        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El nombre de la especialidad es obligatorio.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Insertar especialidad mediante la capa BLL
        int resultado = bllEspecialidad.insertarEspecialidad(nombre);

        if (resultado == 0) {
            limpiarFormulario();
            listarEspecialidadesTabla();
        }
    }

    /**
     * RN-42, RN-46: Actualiza el nombre de una especialidad seleccionada.
     */
    private void modificarEspecialidad() {
        if (especialidadSeleccionada == null) {
            JOptionPane.showMessageDialog(this, "Seleccione una especialidad de la tabla para modificar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String nombre = txtNombreEspecialidad.getText().trim();

        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El nombre de la especialidad no puede estar vacío.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int resultado = bllEspecialidad.actualizarEspecialidad(
                especialidadSeleccionada.getIdEspecialidad(),
                nombre
        );

        if (resultado == 0) {
            limpiarFormulario();
            listarEspecialidadesTabla();
        }
    }

    // 3. CARGA DE TABLA Y SELECCIÓN

    private void listarEspecialidadesTabla() {
        DefaultTableModel model = new DefaultTableModel(
        new String[]{"ID", "Nombre Especialidad"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        ArrayList<Especialidad> lista = bllEspecialidad.listarEspecialidad();
        for (Especialidad esp : lista) {
            model.addRow(new Object[]{
                    esp.getIdEspecialidad(),
                    esp.getNombre(),
                    
            });
        }

        tblEspecialidades.setModel(model);
    }

    private void cargarEspecialidadSeleccionada() {
        int fila = tblEspecialidades.getSelectedRow();
        if (fila != -1) {
            int idEsp = (int) tblEspecialidades.getValueAt(fila, 0);
            this.especialidadSeleccionada = bllEspecialidad.buscarEspecialidad(idEsp);

            if (especialidadSeleccionada != null) {
                txtNombreEspecialidad.setText(especialidadSeleccionada.getNombre());
            }
        }
    }

    private void limpiarFormulario() {

        txtNombreEspecialidad.setText("");

        this.especialidadSeleccionada = null;

        tblEspecialidades.clearSelection();

    }

