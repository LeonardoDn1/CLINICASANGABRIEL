    private void btnBuscarAtencionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarAtencionActionPerformed
        // TODO add your handling code here:
        String idAtencionStr = txtAtencionId.getText().trim();
        if (idAtencionStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el N° de Atención.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int idAtencion = Integer.parseInt(idAtencionStr);
            AtencionMedica atencion = bllAtencion.buscarAtencion(idAtencion);

            if (atencion == null) {
                JOptionPane.showMessageDialog(this, "La atención médica ingresada no existe.", "Error", JOptionPane.ERROR_MESSAGE);
                limpiarPantalla();
                return;
            }

            Pago pagoExistente = bllPago.buscarPorAtencion(idAtencion);
            if (pagoExistente != null) {
                Comprobante comprobante = bllComprobante.buscarComprobantePorPago(pagoExistente.getIdPago());
                JOptionPane.showMessageDialog(this,
                        "Esta atención médica ya cuenta con un pago registrado (Pago N° " + pagoExistente.getIdPago() + ").",
                        "Información", JOptionPane.INFORMATION_MESSAGE);
                cargarDatosPagoExistente(pagoExistente, comprobante);
                return;
            }

            cargarDatosAtencion(atencion);
            JOptionPane.showMessageDialog(this, "Atención encontrada. Proceda con el pago.", "Información", JOptionPane.INFORMATION_MESSAGE);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El N° de Atención debe ser un número entero válido.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarAtencionActionPerformed

    private void btnProcesarPagoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcesarPagoActionPerformed
        // TODO add your handling code here:
        if (atencionSeleccionada == null) {
            JOptionPane.showMessageDialog(this, "Primero busque una Atención Médica válida.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String metodoSeleccionado = (String) cmbMetodoPago.getSelectedItem();
        String tipoComprobante = (String) cmbTipoComprobante.getSelectedItem();

        if (metodoSeleccionado == null || metodoSeleccionado.startsWith("Seleccione")
                || tipoComprobante == null || tipoComprobante.startsWith("Seleccione")) {
            JOptionPane.showMessageDialog(this, "Seleccione un Método de Pago y un Tipo de Comprobante.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        this.documentoCliente = txtDocumento.getText().trim();
        this.nombreCliente = txtNombreCliente.getText().trim();

        if (this.documentoCliente.isEmpty() || this.nombreCliente.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese los datos del cliente para generar el comprobante.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String tipoComprobanteBD = tipoComprobante.toUpperCase();
        String metodoPagoBD = switch (metodoSeleccionado) {
            case "Tarjeta" ->
                "TARJETA";
            case "Transferencia" ->
                "TRANSFERENCIA";
            case "Billetera electrónica" ->
                "BILLETERA_ELECTRONICA";
            default ->
                "EFECTIVO";
        };

        BigDecimal monto = new BigDecimal(txtMontoTotal.getText().trim().replace("S/ ", ""));
        int idCajeroLogueado = (usuarioActual != null) ? usuarioActual.getIdUsuario() : 1;

        int resPago = bllPago.insertarPago(
                atencionSeleccionada.getIdAtencion(),
                idCajeroLogueado,
                monto,
                metodoPagoBD,
                tipoComprobanteBD
        );

        if (resPago == 0) {
            this.pagoProcesado = bllPago.buscarPorAtencion(atencionSeleccionada.getIdAtencion());

            if (pagoProcesado != null) {
                this.comprobanteGenerado = bllComprobante.buscarComprobantePorPago(pagoProcesado.getIdPago());

                if (comprobanteGenerado != null) {
                    txtNroComprobante.setText(comprobanteGenerado.getNumeroComprobante());
                } else {
                    txtNroComprobante.setText("BOL-" + String.format("%06d", pagoProcesado.getIdPago()));
                }

                btnProcesarPago.setEnabled(false);
                btnImprimirComprobante.setEnabled(true);

                JOptionPane.showMessageDialog(this, "Pago procesado y comprobante generado exitosamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnProcesarPagoActionPerformed

