    private void configurarEventos() {
        // Los botones ahora se manejan desde los métodos actionPerformed de abajo.
        // Solo dejamos el listener de selección de la tabla.
        tblMedicamentosCatalogo.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && tblMedicamentosCatalogo.getSelectedRow() != -1) {
                cargarSeleccionDesdeTabla();
            }
        });
    }

    private void listarMedicamentosTabla() {
        DefaultTableModel model = new DefaultTableModel(
                new String[]{"Código", "Nombre", "Presentación", "Stock Actual", "Stock Mínimo", "Precio Unitario"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        ArrayList<Medicamento> lista = bllMedicamento.listarMedicamentos();
        for (Medicamento m : lista) {
            model.addRow(new Object[]{
                m.getIdMedicamento(),
                m.getNombre(),
                m.getUnidadMedida(),
                m.getStockActual(),
                m.getStockMinimo(),
                "S/ " + m.getPrecioUnitario()
            });
        }

        tblMedicamentosCatalogo.setModel(model);
    }

    private void cargarSeleccionDesdeTabla() {
        int fila = tblMedicamentosCatalogo.getSelectedRow();
        if (fila != -1) {
            int idMed = (int) tblMedicamentosCatalogo.getValueAt(fila, 0);
            this.medicamentoSeleccionado = bllMedicamento.buscarMedicamento(idMed);

            if (medicamentoSeleccionado != null) {
                txtCodigo.setText(String.valueOf(medicamentoSeleccionado.getIdMedicamento()));
                txtNombreMedicamento.setText(medicamentoSeleccionado.getNombre());
                txtPresentacion.setText(medicamentoSeleccionado.getUnidadMedida());
                txtStockActual.setText(String.valueOf(medicamentoSeleccionado.getStockActual()));
                txtStockMinimo.setText(String.valueOf(medicamentoSeleccionado.getStockMinimo()));
                txtPrecio.setText(medicamentoSeleccionado.getPrecioUnitario().toString());
            }
        }
    }

