    private void btnGuardarMedicamentoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarMedicamentoActionPerformed
        // TODO add your handling code here:
        String nombre = txtNombreMedicamento.getText().trim();
        String presentacion = txtPresentacion.getText().trim(); // Unidad de medida (ej. Blíster, Jarabe, Caja)
        String stockActualStr = txtStockActual.getText().trim();
        String stockMinimoStr = txtStockMinimo.getText().trim();
        String precioStr = txtPrecio.getText().trim();

        // Validar datos obligatorios
        if (nombre.isEmpty() || presentacion.isEmpty() || stockActualStr.isEmpty() || stockMinimoStr.isEmpty() || precioStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor complete todos los campos requeridos.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int stockActual = Integer.parseInt(stockActualStr);
            int stockMinimo = Integer.parseInt(stockMinimoStr);
            BigDecimal precio = new BigDecimal(precioStr);

            if (stockActual < 0 || stockMinimo < 0 || precio.compareTo(BigDecimal.ZERO) < 0) {
                JOptionPane.showMessageDialog(this, "El stock y el precio deben ser valores mayores o iguales a cero.", "Advertencia", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Insertar medicamento
            int resultado = bllMedicamento.insertarMedicamento(
                    nombre,
                    "Presentación: " + presentacion,
                    presentacion,
                    stockActual,
                    stockMinimo,
                    precio
            );

            if (resultado == 0) {
                // LOGICA DE LIMPIEZA DIRECTAMENTE AQUÍ
                txtCodigo.setText("");
                txtNombreMedicamento.setText("");
                txtPresentacion.setText("");
                txtStockActual.setText("");
                txtStockMinimo.setText("");
                txtPrecio.setText("");
                this.medicamentoSeleccionado = null;
                tblMedicamentosCatalogo.clearSelection();

                listarMedicamentosTabla();
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El stock debe ser un número entero y el precio un valor numérico decimal válido.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarMedicamentoActionPerformed

    private void btnModificarStockActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarStockActionPerformed
        // TODO add your handling code here:
        if (medicamentoSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "Seleccione un medicamento de la tabla para modificar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String nombre = txtNombreMedicamento.getText().trim();
        String presentacion = txtPresentacion.getText().trim();
        String stockActualStr = txtStockActual.getText().trim();
        String stockMinimoStr = txtStockMinimo.getText().trim();
        String precioStr = txtPrecio.getText().trim();

        if (nombre.isEmpty() || stockActualStr.isEmpty() || precioStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete los campos obligatorios para actualizar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int stockActual = Integer.parseInt(stockActualStr);
            int stockMinimo = Integer.parseInt(stockMinimoStr);
            BigDecimal precio = new BigDecimal(precioStr);

            int resultado = bllMedicamento.actualizarMedicamento(
                    medicamentoSeleccionado.getIdMedicamento(),
                    nombre,
                    "Presentación: " + presentacion,
                    presentacion,
                    stockActual,
                    stockMinimo,
                    precio
            );

            if (resultado == 0) {
                // LOGICA DE LIMPIEZA DIRECTAMENTE AQUÍ
                txtCodigo.setText("");
                txtNombreMedicamento.setText("");
                txtPresentacion.setText("");
                txtStockActual.setText("");
                txtStockMinimo.setText("");
                txtPrecio.setText("");
                this.medicamentoSeleccionado = null;
                tblMedicamentosCatalogo.clearSelection();
                
                listarMedicamentosTabla();
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Verifique que los valores numéricos sean correctos.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnModificarStockActionPerformed

