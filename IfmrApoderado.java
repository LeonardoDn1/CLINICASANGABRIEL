    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        if (txtDni.getText().trim().isEmpty() || txtNombres.getText().trim().isEmpty() || txtApellidos.getText().trim().isEmpty()
                || txtTelefono.getText().trim().isEmpty() || txtParentesco.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete los datos del apoderado", "Advertencia", 2);
            return;
        }

        Apoderado datosApoderado = new Apoderado();

        if (modoEdicion) {
            datosApoderado.setIdApoderado(apoderado.getIdApoderado());
            datosApoderado.setIdPaciente(apoderado.getIdPaciente());
        }

        datosApoderado.setDni(txtDni.getText().trim());
        datosApoderado.setNombres(txtNombres.getText().trim());
        datosApoderado.setApellidos(txtApellidos.getText().trim());
        datosApoderado.setTelefono(txtTelefono.getText().trim());
        datosApoderado.setParentesco(txtParentesco.getText().trim());

        if (!bllApoderado.validarApoderado(datosApoderado)) {
            JOptionPane.showMessageDialog(this, "Datos del apoderado incorrectos", "Error", 0);
            txtDni.setText("");
            txtNombres.setText("");
            txtApellidos.setText("");
            txtTelefono.setText("");
            txtParentesco.setText("");
            txtDni.requestFocus();
            return;
        }

        if (modoEdicion) {
            int resultado = bllApoderado.actualizarApoderado(datosApoderado);

            if (resultado == 0) {
                apoderado = datosApoderado;
                this.dispose();
            }
        } else {
            apoderado = datosApoderado;
            formularioPaciente.setApoderadoTemporal(apoderado);
            JOptionPane.showMessageDialog(this, "Datos del apoderado cargados correctamente", "Información", 1);
            this.dispose();
        }
    }//GEN-LAST:event_btnGuardarActionPerformed


