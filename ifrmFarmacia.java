    private void btnEntregarMedicamentosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntregarMedicamentosActionPerformed
        if (recetaActual == null || detallesActuales == null || detallesActuales.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Busque una receta válida antes de registrar la entrega.",
                    "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 1. Validar que TODOS los medicamentos tengan stock suficiente
        for (RecetaDetalle rd : detallesActuales) {
            boolean stockOk = bllMedicamento.verificarStock(rd.getIdMedicamento(), rd.getCantidad());
            if (!stockOk) {
                Medicamento m = bllMedicamento.buscarMedicamento(rd.getIdMedicamento());
                String nombreMed = (m != null) ? m.getNombre() : "ID " + rd.getIdMedicamento();
                JOptionPane.showMessageDialog(this,
                        "No se puede procesar la entrega. Stock insuficiente para el medicamento: " + nombreMed,
                        "Error de Stock", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }

        // Obtener ID dinámicamente desde el usuario en sesión
        int idFarmaceuticoLogueado = (usuarioActual != null) ? usuarioActual.getIdUsuario() : 13;

        // 2. Registrar las entregas (El Stored Procedure descuenta el inventario internamente)
        boolean todoCorrecto = true;
        for (RecetaDetalle rd : detallesActuales) {
            int resEntrega = bllEntrega.insertarEntregaMedicamento(
                    rd.getIdRecetaDetalle(), idFarmaceuticoLogueado, rd.getCantidad());

            if (resEntrega != 0) {
                todoCorrecto = false;
            }
        }

        if (todoCorrecto) {
            JOptionPane.showMessageDialog(this,
                    "Entrega de medicamentos registrada y stock actualizado en inventario.",
                    "Éxito", JOptionPane.INFORMATION_MESSAGE);
            limpiarPantallaBusqueda();
            cargarAlertasStockMinimo();
        }
    }//GEN-LAST:event_btnEntregarMedicamentosActionPerformed

    private void btnBuscarRecetaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarRecetaActionPerformed
        // TODO add your handling code here:
        // BUSCAR RECETA
        String busquedaStr = txtBuscarReceta.getText().trim();
        if (busquedaStr.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el N° de Receta o N° de Atención.",
                    "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int idCodigo = Integer.parseInt(busquedaStr);

            // Intentar buscar por ID de Receta
            this.recetaActual = bllReceta.buscarReceta(idCodigo);

            // Si no encuentra por ID de Receta, buscar por ID de Atención
            if (recetaActual == null) {
                this.recetaActual = bllReceta.buscarPorAtencion(idCodigo);
            }

            if (recetaActual == null) {
                JOptionPane.showMessageDialog(this,
                        "No se encontró ninguna receta con el código ingresado.",
                        "Error", JOptionPane.ERROR_MESSAGE);
                limpiarPantallaBusqueda();
                return;
            }

            // Cargar datos del Paciente asociado a través de la Atención Médica
            AtencionMedica atencion = bllAtencion.buscarAtencion(recetaActual.getIdAtencion());
            if (atencion != null) {
                // Obtener cita asociada para llegar al paciente
                BLLCita bllCita = new BLLCita();
                var cita = bllCita.buscarCita(atencion.getIdCita());
                if (cita != null) {
                    Paciente paciente = bllPaciente.buscarPaciente(cita.getIdPaciente());
                    if (paciente != null) {
                        txtPaciente.setText(paciente.getNombres() + " " + paciente.getApellidos()
                                + " (DNI: " + paciente.getDni() + ")");
                    }
                }
            }

            // Cargar detalle de la receta en la tabla
            cargarTablaDetalleReceta(recetaActual.getIdReceta());

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "El código ingresado debe ser un número entero válido.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarRecetaActionPerformed

